#define HID_REPORT_VALUE(type, id) (((type) << 8) | (id))
struct hid_boot_keyboard_report {
	uint8_t modifiers, reserved, keys[HID_BOOT_KEY_SLOTS];
};
struct hid_boot_mouse_report {
	uint8_t buttons;
	int8_t x, y;
};
struct hid_extended_mouse_report {
	struct hid_boot_mouse_report boot;
	int8_t wheel;
};
_Static_assert(sizeof(struct hid_boot_keyboard_report) == 8,
	       "HID boot keyboard report size");
_Static_assert(sizeof(struct hid_boot_mouse_report) == 3,
	       "HID boot mouse report size");
